"""Put rendered mixes on the demo page: MP3 copies in demo/mixes/ plus demo/mixes/mixes.js (tracklists, waveforms).

Run after export_demo_library.py (each song's genres and moods come from demo/library.json), inside WSL:
    wsl -d Ubuntu-24.04 -u root -- bash -c "source ~/autodj-env/bin/activate && python /mnt/c/Users/aziba/OneDrive/Desktop/AutoDj/python/export_demo_mixes.py"
"""

import json
import os
import subprocess

import numpy as np
from pedalboard.io import AudioFile

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
MIX_DIR = os.path.join(BASE_DIR, "renders", "mix")
DEMO_DIR = os.path.join(os.path.dirname(BASE_DIR), "demo")
OUT_DIR = os.path.join(DEMO_DIR, "mixes")
PEAKS = 600  # waveform resolution; the page resamples it to however many bars fit

# Rendered mix -> name shown on the page
MIXES = {
    "rnb_late_night": "Late-night R&B",
    "house": "House",
    "test_mix": "Mix 1",
    "test_mix_2": "Mix 2",
}


def peaks(path):
    """Loudness envelope of the mix, PEAKS values scaled 0-1."""
    with AudioFile(path) as f:
        audio = f.read(f.frames).mean(axis=0)
    chunks = np.array_split(audio, PEAKS)
    rms = np.array([np.sqrt(np.mean(c ** 2)) for c in chunks])
    return [round(float(v), 3) for v in rms / rms.max()]


def main():
    library = {s["title"]: s for s in json.load(open(os.path.join(DEMO_DIR, "library.json"), encoding="utf-8"))}
    os.makedirs(OUT_DIR, exist_ok=True)
    mixes = []

    for name, label in MIXES.items():
        wav, plan_path = os.path.join(MIX_DIR, name + ".wav"), os.path.join(MIX_DIR, name + ".json")
        plan = json.load(open(plan_path, encoding="utf-8"))
        mp3 = os.path.join(OUT_DIR, name + ".mp3")
        if not os.path.exists(mp3) or os.path.getmtime(mp3) < os.path.getmtime(wav):
            print(f"encoding {name}.mp3 ...")
            subprocess.run(["ffmpeg", "-nostdin", "-v", "error", "-y", "-i", wav, "-codec:a", "libmp3lame", "-b:a", "192k", mp3], check=True)

        # A song takes over at its transition's bass swap (half the overlap after the transition starts)
        bar = 4 * 60 / plan["bpm"]
        tracklist = []
        for i, t in enumerate(plan["tracklist"]):
            song = library.get(t["title"], {})
            entry = {"title": t["title"].split(" (feat.")[0], "artist": t["artist"], "start": t["time"],
                     "genres": song.get("genres", []), "energy": song.get("energy"), "moods": song.get("moods")}
            if i:
                overlap = plan["transitions"][i - 1]["overlap"]
                entry["swap"] = round(t["time"] + overlap / 2 * bar, 2)
                entry["blendEnd"] = round(t["time"] + overlap * bar, 2)
            tracklist.append(entry)

        mixes.append({"id": name, "name": label, "file": f"mixes/{name}.mp3", "length": plan["length"],
                      "bpm": plan["bpm"], "tracklist": tracklist, "peaks": peaks(wav)})
        print(f"{label}: {' -> '.join(t['title'] for t in tracklist)}  ({plan['length'] / 60:.1f} min)")

    with open(os.path.join(OUT_DIR, "mixes.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by python/export_demo_mixes.py\nwindow.AUTODJ_MIXES = ")
        json.dump(mixes, f, ensure_ascii=False)
        f.write(";\n")
    print(f"\n{len(mixes)} mixes -> {OUT_DIR}")


if __name__ == "__main__":
    main()
